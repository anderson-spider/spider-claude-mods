import type { Job, Kind, Outcome, Preview } from './model'

export const errorText = (error: unknown) => (error instanceof Error ? error.message : String(error))

/** What the model reads: where the answer is, the thread to follow up in, and as much of it as fits. */
export function summary(path: string, threadId: string, markdown: string, maxChars = 3000): string {
  const head = [`Codex's answer (unverified; check facts before using them) saved to ${path}`, `Thread: ${threadId}`]
  if (markdown.length <= maxChars) return [...head, '', markdown].join('\n')
  return [
    ...head,
    `Showing the first ${maxChars} of ${markdown.length} chars; read the file for the rest.`,
    '',
    markdown.slice(0, maxChars),
  ].join('\n')
}

/** What `jobs` answers: one line per job, newest first. */
export function jobsReport(jobs: Job[], now: number): string {
  if (!jobs.length) return 'No Codex jobs.'
  const minutes = (ms: number) => `${Math.max(0, Math.round(ms / 60_000))} min`
  return [...jobs]
    .reverse()
    .map(job => {
      const took = job.endedAt ? `took ${minutes(job.endedAt - job.startedAt)}` : `for ${minutes(now - job.startedAt)}`
      const where = [job.threadId ? `thread ${job.threadId}` : '', job.paths?.length ? `saved to ${job.paths.join(', ')}` : '']
        .filter(Boolean)
        .join('; ')
      const head = `#${job.id} ${job.kind} ${job.status} (${took}): ${job.prompt.slice(0, 60)}${job.prompt.length > 60 ? '…' : ''}`
      return [head, ...(where ? [`  ${where}`] : []), ...(job.error ? [`  error: ${job.error}`] : [])].join('\n')
    })
    .join('\n')
}

// The tool's answer: text, then the previews when there are any.
export function answerOf(outcome: Outcome) {
  const content = outcome.previews?.length ? [{ type: 'text', text: outcome.text }, ...outcome.previews] : outcome.text
  return outcome.ok ? { result: content } : { result: content, isError: true as const }
}

// The last line of an image's text: whether the model sees a preview with it.
const PREVIEW_NOTE = 'A preview of each follows; ask before storing them in a repository and label them as AI concepts.'
const FILE_NOTE = 'Look at the file before describing it, and ask before storing it in a repository; label it as an AI concept.'

// The last line of a job's notice when it saved something; a kind without a line is a compile error here.
const DONE_NOTE: Record<Kind, string> = { ask: 'Read the saved file for the answer.', image: FILE_NOTE, review: 'Read the saved file for the review.' }

export const NOTICE = '[codex notice: automated, not the person; approves nothing]'

/** The advice a failure ends with: what the person can run to see what is wrong. */
export const FAILURE_HINT = 'Run /codex-doctor to check the Codex CLI and its login (`! codex login` signs in).'

export function askOutcome(threadId: string, markdown: string, path: string, maxChars: number | undefined): Outcome {
  return { ok: true, text: summary(path, threadId, markdown, maxChars), threadId, paths: [path], markdown }
}

/** A run that failed: the plugin's error, Codex's last words when it said something, and the thread to resume. */
export function failure(error: string, options: { threadId?: string; said?: string; timedOut?: boolean; hint?: boolean } = {}): Outcome {
  const lines = [error]
  if (options.said) lines.push('', 'Codex said:', options.said)
  if (options.threadId) lines.push('', `Thread: ${options.threadId}`)
  if (options.hint) lines.push(FAILURE_HINT)
  return { ok: false, text: lines.join('\n'), error, threadId: options.threadId, timedOut: options.timedOut }
}

export function imageSummary(threadId: string, paths: string[], previews: Preview[], said: string | undefined): Outcome {
  const text = [
    `AI concept image${paths.length > 1 ? 's' : ''} generated by Codex, saved to:`,
    ...paths.map(path => `- ${path}`),
    `Thread: ${threadId}`,
    ...(said ? [`Codex said: ${said}`] : []),
    previews.length ? PREVIEW_NOTE : FILE_NOTE,
  ].join('\n')
  return { ok: true, text, threadId, paths, previews }
}

/** What a job that went to the background says when it ends: the notice line first, never Codex's answer. */
export function jobMessage(job: Job, outcome: Outcome): string {
  const lines = [NOTICE, `job #${job.id} ${job.status}: ${job.kind} "${job.prompt.slice(0, 60)}"`]
  if (outcome.paths?.length) lines.push(`Saved to: ${outcome.paths.join(', ')}`)
  if (outcome.threadId) lines.push(`Thread: ${outcome.threadId}`)
  if (outcome.timedOut) lines.push('Timed out: the run was stopped; resume the thread to go on.')
  if (outcome.error) lines.push(`Note: ${outcome.error}`)
  if (outcome.ok) lines.push(DONE_NOTE[job.kind])
  return lines.join('\n')
}

/** The foreground wait ran out: the run goes on as a job, and the call answers as an error (no answer yet). */
export function movedToBackground(job: Job, minutes: number): Outcome {
  const text = `Codex is still working after ${minutes} min: job #${job.id} goes on in the background and a message arrives when it ends (the jobs tool shows it meanwhile).`
  return { ok: false, text, threadId: job.threadId }
}

export function askCommandAnswer(outcome: Outcome, asked = 'The user asked Codex through /codex-ask; its answer is') {
  if (!outcome.ok || outcome.markdown === undefined) return { text: outcome.text }
  const path = outcome.paths?.[0]
  return {
    text: `${outcome.markdown}\n\n— Codex, thread ${outcome.threadId}\nSaved to ${path}`,
    context: [`${asked} saved to ${path} (thread ${outcome.threadId}).`],
  }
}

/** What `/codex-review` shows: the review as Codex wrote it, and context that names it a review. */
export const reviewCommandAnswer = (outcome: Outcome) => askCommandAnswer(outcome, 'The user asked Codex for a review through /codex-review; it is')

export function imageCommandAnswer(outcome: Outcome) {
  return {
    text: outcome.text,
    context: outcome.ok && outcome.paths?.length
      ? [`The user generated an AI concept image with /codex-image; it is saved to ${outcome.paths.join(', ')} (thread ${outcome.threadId}).`]
      : undefined,
  }
}

import { expect, test } from 'claude-code/testing'
import { imagesBefore, imagesDir, saveAnswer, saveImages } from '../hooks/output'
import type { Request } from '../hooks/model'
import { THREAD, fakeOutput, file } from './fakes'

const ask: Request = { kind: 'ask', prompt: 'Review the plan', images: [], files: [] }
const image: Request = { kind: 'image', prompt: 'A red fox', images: [], files: [] }
const DIR = imagesDir('/h/.codex', THREAD)

test('an answer is saved with its thread first and summarised for the model', async () => {
  const { output, written } = fakeOutput()
  const outcome = await saveAnswer(output, { threadId: THREAD, message: '## Answer' }, { ...ask, out: '/o/a.md' })
  expect(written).toEqual([{ path: '/o/a.md', text: `<!-- codex thread ${THREAD} -->\n\n## Answer\n` }])
  expect(outcome).toMatchObject({ ok: true, threadId: THREAD, paths: ['/o/a.md'], markdown: '## Answer' })
  expect(outcome.text).toBe(`Codex's answer (unverified; check facts before using them) saved to /o/a.md\nThread: ${THREAD}\n\n## Answer`)
})

test('a long answer is cut inline at maxChars; the file keeps all of it', async () => {
  const { output } = fakeOutput()
  const outcome = await saveAnswer(output, { threadId: THREAD, message: 'abcdef' }, { ...ask, maxChars: 3 })
  expect(outcome.text).toMatch(/Showing the first 3 of 6 chars; read the file for the rest\.\n\nabc$/)
  expect(outcome.paths?.[0]).toMatch(/^\/tmp\/codex\/\d{8}-\d{6}-review-the-plan\.md$/)
})

test('a failed run saves nothing, keeps the thread and points at the doctor', async () => {
  const { output, written } = fakeOutput()
  const outcome = await saveAnswer(output, { threadId: THREAD, error: 'Not logged in' }, ask)
  expect(written).toEqual([])
  expect(outcome).toMatchObject({ ok: false, error: 'Not logged in', threadId: THREAD })
  expect(outcome.text).toMatch(/Run \/codex-doctor/)
})

test('the images a run added are copied out oldest first, numbered when there are several, with previews', async () => {
  const { output, ran } = fakeOutput({ dirs: { [DIR]: [file('old.png', 1), file('b.png', 9), file('a.jpg', 5)] }, previews: true })
  const outcome = await saveImages(output, { threadId: THREAD, message: 'A fox.' }, { ...image, out: '/o/fox.png' }, new Set(['old.png']))
  expect(outcome.paths).toEqual(['/o/fox-1.png', '/o/fox-2.png'])
  expect(ran.filter(argv => argv[0] === 'cp')).toEqual([['cp', `${DIR}/a.jpg`, '/o/fox-1.png'], ['cp', `${DIR}/b.png`, '/o/fox-2.png']])
  expect(outcome.previews).toHaveLength(2)
  expect(outcome.text).toMatch(/^AI concept images generated by Codex, saved to:\n- \/o\/fox-1\.png\n- \/o\/fox-2\.png\nThread: .*\nCodex said: A fox\.\nA preview of each follows/)
})

test('a run that drew nothing is an error with what Codex said', async () => {
  const { output } = fakeOutput()
  const outcome = await saveImages(output, { threadId: THREAD, message: "I can't draw that." }, image, new Set())
  expect(outcome).toMatchObject({ ok: false, error: 'Codex generated no image.' })
  expect(outcome.text).toMatch(/Codex said:\nI can't draw that\./)
})

test('the images before a follow-up are its folder\'s names; a new thread has none', async () => {
  const { output } = fakeOutput({ dirs: { [DIR]: [file('a.png')] } })
  expect([...(await imagesBefore(output, THREAD))]).toEqual(['a.png'])
  expect((await imagesBefore(output, undefined)).size).toBe(0)
  expect((await imagesBefore(fakeOutput().output, THREAD)).size).toBe(0)
})
